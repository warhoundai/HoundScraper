"""Record the tested dependency closure. Run in the tested Python 3.12 environment."""
import importlib.metadata as md,json,tomllib
from pathlib import Path
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name
root=Path(__file__).parents[1];project=tomllib.loads((root/'pyproject.toml').read_text())['project']
def closure(initial):
    found={};visited=set()
    def visit(spec):
        requirement=Requirement(spec);name=canonicalize_name(requirement.name);identity=(name,tuple(sorted(requirement.extras)))
        if identity in visited:return
        visited.add(identity);dist=md.distribution(name);found[name]=dist.version
        for raw in dist.requires or []:
            req=Requirement(raw)
            if not req.marker or any(req.marker.evaluate({'extra':extra}) for extra in {'',*requirement.extras}):visit(str(req))
    for spec in initial:visit(spec)
    return found
runtime=closure(project['dependencies']);dev=closure(project['dependencies']+project['optional-dependencies']['dev']+project['optional-dependencies']['browser'])
for filename,items in [('requirements.lock',runtime),('requirements-dev.lock',dev)]:
    (root/filename).write_text('# Tested on Python 3.12; generated by scripts/lock-environment.py\n'+''.join(f'{n}=={v}\n' for n,v in sorted(items.items())))
inventory=[]
for name,version in sorted(runtime.items()):
    d=md.metadata(name);license=d.get('License-Expression') or d.get('License') or '; '.join(x.split(' :: ')[-1] for x in d.get_all('Classifier',[]) if x.startswith('License ::'))
    inventory.append({'name':name,'version':version,'license':license.splitlines()[0][:250] if license else 'UNDECLARED'})
(root/'docs/dependencies.json').write_text(json.dumps(inventory,indent=2)+'\n')
print({'runtime_packages':len(runtime),'development_packages':len(dev)})
